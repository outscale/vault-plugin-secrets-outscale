package outscalevault

import (
	"context"
	"errors"
	"fmt"
	"time"

	"github.com/hashicorp/vault/sdk/framework"
	"github.com/hashicorp/vault/sdk/helper/template"
	"github.com/hashicorp/vault/sdk/logical"
	"github.com/outscale/osc-sdk-go/v3/pkg/iso8601"
	"github.com/outscale/osc-sdk-go/v3/pkg/osc"
)

func pathUserCreds(b *backend) *framework.Path {
	return &framework.Path{
		Pattern: "creds/" + framework.GenericNameRegex("name"),
		Fields: map[string]*framework.FieldSchema{
			"name": {
				Type:        framework.TypeLowerCaseString,
				Description: "Name of the role",
				Required:    true,
			},
		},
		Callbacks: map[logical.Operation]framework.OperationFunc{
			logical.ReadOperation:   b.pathUserCredsRead,
			logical.UpdateOperation: b.pathUserCredsRead,
		},
		HelpSynopsis:    pathUserCredsHelpSynopsis,
		HelpDescription: pathUserCredsHelpDescription,
	}
}

func (b *backend) pathUserCredsRead(
	ctx context.Context,
	req *logical.Request,
	d *framework.FieldData,
) (*logical.Response, error) {
	roleName := d.Get("name").(string)

	roleEntry, err := b.getRole(ctx, req.Storage, roleName)
	if err != nil {
		return nil, fmt.Errorf("error retriving role: %w", err)
	}

	if roleEntry == nil {
		return nil, errors.New("error retriving role: role is nil")
	}

	return b.createUserCreds(ctx, req, roleEntry, roleName)
}

func (b *backend) createUserCreds(
	ctx context.Context,
	req *logical.Request,
	roleEntry *outscaleRoleEntry,
	roleName string,
) (*logical.Response, error) {
	client, err := b.getClient(ctx, req.Storage)
	if err != nil {
		return nil, err
	}

	createUserRequest := osc.CreateUserRequest{}

	up, err := template.NewTemplate(template.Template(roleEntry.UserNameTemplate))
	if err != nil {
		return nil, fmt.Errorf("unable to initialize username template: %w", err)
	}

	createUserRequest.UserName, err = up.Generate(nil)
	if err != nil {
		return nil, fmt.Errorf("failed to generate username: %w", err)
	}
	if len(createUserRequest.UserName) > 64 {
		return nil, fmt.Errorf(
			"the username generated by the template exceeds the EIM username length limits of 64 chars",
		)
	}

	if roleEntry.UserEmailTemplate != "" {
		up, err := template.NewTemplate(template.Template(roleEntry.UserEmailTemplate))
		if err != nil {
			return nil, fmt.Errorf("unable to initialize email template: %w", err)
		}

		tmp, err := up.Generate(nil)
		if err != nil {
			return nil, fmt.Errorf("failed to generate email: %w", err)
		}
		createUserRequest.UserEmail = &tmp
	}

	if roleEntry.PathTemplate != "" {
		up, err := template.NewTemplate(template.Template(roleEntry.PathTemplate))
		if err != nil {
			return nil, fmt.Errorf("unable to initialize path template: %w", err)
		}

		tmp, err := up.Generate(nil)
		if err != nil {
			return nil, fmt.Errorf("failed to generate path: %w", err)
		}
		createUserRequest.UserEmail = &tmp
	}

	createUserResponse, err := client.CreateUser(ctx, createUserRequest)
	if err != nil {
		return nil, fmt.Errorf("error creating EIM user: %w", err)
	}

	for _, userGroupName := range roleEntry.UserGroupNames {
		_, err := client.AddUserToUserGroup(ctx, osc.AddUserToUserGroupRequest{
			UserName:      *createUserResponse.User.UserName,
			UserGroupName: userGroupName,
		})
		if err != nil {
			return nil, fmt.Errorf("error adding user to group: %w", err)
		}
	}

	tag := fmt.Sprintf("vault:creds/%s", roleName)
	createAccessKey, err := client.CreateAccessKey(ctx, osc.CreateAccessKeyRequest{
		UserName:       createUserResponse.User.UserName,
		ExpirationDate: &iso8601.Time{Time: time.Now().Add(roleEntry.TTL)},
		Tag:            &tag,
	})
	if err != nil {
		return nil, fmt.Errorf("error creating AK/SK: %w", err)
	}

	var ttl time.Duration
	if createAccessKey.AccessKey.ExpirationDate != nil {
		ttl = time.Until(createAccessKey.AccessKey.ExpirationDate.Time)
	}

	resp := b.Secret(secretUserAccessKeyType).Response(map[string]any{
		"access_key": *createAccessKey.AccessKey.AccessKeyId,
		"secret_key": *createAccessKey.AccessKey.SecretKey,
	}, map[string]any{
		"username": *createUserResponse.User.UserName,
		"role":     roleName,
	})

	resp.Secret.TTL = ttl
	if roleEntry.MaxTTL > 0 {
		resp.Secret.MaxTTL = roleEntry.MaxTTL
	}
	resp.Secret.Renewable = false

	return resp, nil
}

func secretUserAccessKeys(b *backend) *framework.Secret {
	return &framework.Secret{
		Type: secretUserAccessKeyType,
		Fields: map[string]*framework.FieldSchema{
			"access_key": {
				Type:        framework.TypeString,
				Description: "Access Key",
			},
			"secret_key": {
				Type:        framework.TypeString,
				Description: "Secret Key",
			},
		},
		Revoke: b.secretUserAccessKeyRevoke,
	}
}

func (b *backend) secretUserAccessKeyRevoke(
	ctx context.Context,
	req *logical.Request,
	d *framework.FieldData,
) (*logical.Response, error) {
	// Get the username from the internal data
	usernameRaw, ok := req.Secret.InternalData["username"]
	if !ok {
		return nil, fmt.Errorf("secret is missing username internal data")
	}
	username, ok := usernameRaw.(string)
	if !ok {
		return nil, fmt.Errorf("secret is missing username internal data")
	}

	client, err := b.getClient(ctx, req.Storage)
	if err != nil {
		return nil, err
	}

	readAccessKeysResponse, err := client.ReadAccessKeys(ctx, osc.ReadAccessKeysRequest{
		UserName: &username,
	})
	if err != nil {
		return nil, fmt.Errorf("error reading IEM user access keys: %w", err)
	}

	for _, accessKey := range *readAccessKeysResponse.AccessKeys {
		_, err := client.UpdateAccessKey(ctx, osc.UpdateAccessKeyRequest{
			AccessKeyId: *accessKey.AccessKeyId,
			State:       "INACTIVE",
			UserName:    &username,
		})
		if err != nil {
			return nil, fmt.Errorf("error updating access key: %w", err)
		}

		_, err = client.DeleteAccessKey(ctx, osc.DeleteAccessKeyRequest{
			AccessKeyId: *accessKey.AccessKeyId,
			UserName:    &username,
		})
		if err != nil {
			return nil, fmt.Errorf("error deleting access key: %w", err)
		}
	}

	readUserGroupsPerUserResponse, err := client.ReadUserGroupsPerUser(
		ctx,
		osc.ReadUserGroupsPerUserRequest{
			UserName: username,
		},
	)
	if err != nil {
		return nil, fmt.Errorf("error reading user groups per user: %w", err)
	}

	for _, userGroup := range *readUserGroupsPerUserResponse.UserGroups {
		_, err := client.RemoveUserFromUserGroup(ctx, osc.RemoveUserFromUserGroupRequest{
			UserGroupName: *userGroup.Name,
			UserName:      username,
		})
		if err != nil {
			return nil, fmt.Errorf("error removing user from user group: %w", err)
		}
	}

	_, err = client.DeleteUser(ctx, osc.DeleteUserRequest{
		UserName: username,
	})
	if err != nil {
		return nil, fmt.Errorf("error deleting user: %w", err)
	}

	return nil, nil
}

const (
	pathUserCredsHelpDescription = ""
	pathUserCredsHelpSynopsis    = ""
	secretUserAccessKeyType      = "user_access_keys"
)
